// Converts Fluent UI System Icons (MIT, https://github.com/microsoft/fluentui-system-icons) into a WPF
// ResourceDictionary. Usage: node build-fluent.mjs <svg-dir> <output.xaml>
// <svg-dir> holds the 20px regular SVGs named like the asset folder in snake case (wifi_1.svg, battery_charge_5.svg),
// downloaded from assets/<Name>/SVG/ic_fluent_<name>_20_regular.svg. No dependencies.
import fs from "node:fs";
import path from "node:path";

const [, , svgDir, outFile] = process.argv;

// file name -> resource key suffix (Fluent.<suffix>); WiFi 1 is the strongest signal, WiFi 4 the weakest
const ICONS = {
  speaker_0: "Speaker0", speaker_1: "Speaker1", speaker_2: "Speaker2", speaker_mute: "SpeakerMute",
  wifi_1: "Wifi4", wifi_2: "Wifi3", wifi_3: "Wifi2", wifi_4: "Wifi1", wifi_off: "WifiOff",
  plug_connected: "Ethernet", bluetooth: "Bluetooth", bluetooth_connected: "BluetoothConnected",
};
for (let i = 0; i <= 10; i++) { ICONS[`battery_${i}`] = `Battery${i}`; ICONS[`battery_charge_${i}`] = `BatteryCharge${i}`; }

const lines = [
  "<!-- Generated by tools/icons/build-fluent.mjs from Fluent UI System Icons (MIT, Microsoft). Do not edit. -->",
  "<!-- 20x20 regular icons, scaled to the 24x24 grid of c:Icon; draw with Filled=\"True\". -->",
  '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
  '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
];
for (const [file, key] of Object.entries(ICONS)) {
  const svg = fs.readFileSync(path.join(svgDir, file + ".svg"), "utf8");
  const d = [...svg.matchAll(/\sd="([^"]+)"/g)].map(m => m[1]).join(" ");
  if (!d || !/^[MmLlHhVvCcSsQqTtAaZz0-9.,\s+-e]+$/.test(d)) throw new Error(`no usable path in ${file}`);
  lines.push(`    <PathGeometry x:Key="Fluent.${key}" FillRule="Nonzero" Figures="${d}">`);
  lines.push('        <PathGeometry.Transform><ScaleTransform ScaleX="1.2" ScaleY="1.2" /></PathGeometry.Transform>');
  lines.push("    </PathGeometry>");
}
lines.push("</ResourceDictionary>", "");
fs.writeFileSync(outFile, lines.join("\r\n"));
console.log(`${Object.keys(ICONS).length} icons -> ${outFile}`);
